// Saliência Sinestésica (Propriocepção Tátil-Visual)
// Esculpir Seda não pode passar a mesma sensação de esculpir Granito Maciço.

pub struct TactileProprioceptionFeedback;

impl TactileProprioceptionFeedback {
    /// Injeta fricção no cursor do mouse e engrossa a oscilação auditiva do Maestro.
    pub fn apply_sensory_friction(material_density: f32) -> f32 {
        // println!("[Sinestesia] Usuário tentando esculpir Tungstênio (Densidade: {}).", material_density);
        // A velocidade de arraste do cursor é punida matematicamente pela densidade do material.
        // Ao mesmo tempo, um harmônico grave é enviado ao driver de som.
        // O corpo do humano "sente" o peso físico daquilo que não existe.
        
        material_density * 0.8
    }
}
