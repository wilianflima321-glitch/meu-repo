#!/usr/bin/env node

import fs from 'node:fs'
import path from 'node:path'

const ROOT = process.cwd()
const MIDDLEWARE_FILE = path.join(ROOT, 'middleware.ts')
const APP_DIR = path.join(ROOT, 'app')
const DOCS_DIR = path.join(ROOT, 'docs')
const REPORT_FILE = path.join(DOCS_DIR, 'PUBLIC_ACCESS_SPINE.md')

const PUBLIC_MARKETING_ROUTES = [
  '/',
  '/pricing',
  '/compare',
  '/customers',
  '/contact',
  '/contact-sales',
  '/docs',
  '/download',
  '/help',
  '/marketplace',
  '/roadmap',
  '/status',
  '/trust',
  '/compliance',
  '/security',
  '/security-policy',
  '/security-acknowledgments',
  '/reliability',
  '/honest-status',
  '/terms',
  '/privacy',
  '/forgot-password',
  '/reset-password',
  '/verify-email',
  '/offline',
]

function routeToPagePath(route) {
  if (route === '/') return path.join(APP_DIR, 'page.tsx')
  const segments = route.split('/').filter(Boolean)
  return path.join(APP_DIR, ...segments, 'page.tsx')
}

function parseMiddlewareList(content, constName) {
  const pattern = new RegExp(`const\\s+${constName}\\s*=\\s*\\[(?<body>[\\s\\S]*?)\\];`)
  const match = content.match(pattern)
  if (!match?.groups?.body) return null
  return [...match.groups.body.matchAll(/'([^']+)'/g)].map((item) => item[1])
}

function isAllowedByPublicMiddleware(route, exactPaths, prefixes) {
  return exactPaths.has(route) || prefixes.some((prefix) => route.startsWith(prefix))
}

function main() {
  const middleware = fs.readFileSync(MIDDLEWARE_FILE, 'utf8')
  const prefixes = parseMiddlewareList(middleware, 'PUBLIC_PATH_PREFIXES')
  if (!prefixes) {
    console.error('[public-access-spine] FAIL missing PUBLIC_PATH_PREFIXES in middleware.ts')
    process.exit(1)
  }

  const exactBody = middleware.match(/const\s+PUBLIC_EXACT_PATHS\s*=\s*new\s+Set\(\[(?<body>[\s\S]*?)\]\);/)?.groups?.body
  if (!exactBody) {
    console.error('[public-access-spine] FAIL missing PUBLIC_EXACT_PATHS in middleware.ts')
    process.exit(1)
  }
  const exactPaths = new Set([...exactBody.matchAll(/'([^']+)'/g)].map((item) => item[1]))

  const failures = []
  const rows = []
  for (const route of PUBLIC_MARKETING_ROUTES) {
    const pagePath = routeToPagePath(route)
    const pageExists = fs.existsSync(pagePath)
    const middlewareAllowed = isAllowedByPublicMiddleware(route, exactPaths, prefixes)
    rows.push({ route, pageExists, middlewareAllowed })
    if (!pageExists) failures.push(`${route}: missing App Router page`)
    if (!middlewareAllowed) failures.push(`${route}: redirects unauthenticated users; add it to the public middleware allowlist`)
  }

  fs.mkdirSync(DOCS_DIR, { recursive: true })
  const report = [
    '# Public Access Spine',
    '',
    'Generated by `npm run qa:public-access-spine`. Public marketing, trust, help, and auth recovery pages must stay reachable before sign-in.',
    '',
    '## Public Route Matrix',
    '',
    '| Route | Page exists | Public in middleware |',
    '|---|---:|---:|',
    ...rows.map((row) => `| ${row.route} | ${row.pageExists ? 'yes' : 'no'} | ${row.middlewareAllowed ? 'yes' : 'no'} |`),
    '',
    '## Policy',
    '',
    '- Public trust, security, compliance, pricing, help, contact, and recovery pages cannot redirect to `/login`.',
    '- Product workspace routes such as `/dashboard`, `/ide`, `/settings`, and `/profile` remain protected.',
    '- Add new marketing routes to this gate when PublicHeader or footer exposes them.',
  ]
  fs.writeFileSync(REPORT_FILE, `${report.join('\n')}\n`, 'utf8')

  if (failures.length > 0) {
    console.error('[public-access-spine] FAIL')
    for (const failure of failures) console.error(`- ${failure}`)
    console.error(`report=${path.relative(ROOT, REPORT_FILE).replace(/\\/g, '/')}`)
    process.exit(1)
  }

  console.log(`[public-access-spine] PASS routes=${rows.length}`)
}

main()
