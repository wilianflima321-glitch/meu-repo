import fs from 'node:fs'
import path from 'node:path'

function rel(root, file) {
  return path.relative(root, file).replace(/\\/g, '/')
}

function fileLabel(file) {
  return String(file).replace(/\\/g, '/')
}

export function writeUxMarketStandardReport({
  root,
  reportFile,
  marketReferences,
  competitorPlaybook,
  surfaceMatrix,
  backlog,
  subareaMatrix,
  results,
}) {
  const lines = []
  lines.push('# UX Market Standard Spine')
  lines.push('')
  lines.push('Generated by `npm run qa:ux-market-standard`. This gate keeps Aethel aligned with the local UX arsenal: mission-first entry, disciplined public chrome, trust-first marketplace, progressive Studio navigation, and no screenshot billboard regressions.')
  lines.push('')
  lines.push('## Market Standards Consulted')
  lines.push('')
  lines.push('| Product | Standard Aethel Must Match | Source |')
  lines.push('| --- | --- | --- |')
  for (const reference of marketReferences) lines.push(`| ${reference.product} | ${reference.standard} | ${reference.source} |`)
  lines.push('')
  lines.push('## Competitor Playbook')
  lines.push('')
  lines.push('| Competitor | Pattern to Copy | Aethel Move |')
  lines.push('| --- | --- | --- |')
  for (const item of competitorPlaybook) lines.push(`| ${item.competitor} | ${item.pattern} | ${item.aethelMove} |`)
  lines.push('')
  lines.push('## Surface Quality Matrix')
  lines.push('')
  lines.push('| Surface | Route | Comparator | Decision | Principle |')
  lines.push('| --- | --- | --- | --- | --- |')
  for (const surface of surfaceMatrix) lines.push(`| ${surface.surface} | \`${surface.route}\` | ${surface.comparator} | ${surface.decision} | ${surface.principle} |`)
  lines.push('')
  lines.push('## Prioritized UX Backlog')
  lines.push('')
  lines.push('| Priority | Area | Action |')
  lines.push('| --- | --- | --- |')
  for (const [priority, area, action] of backlog) lines.push(`| ${priority} | ${area} | ${action} |`)
  lines.push('')
  lines.push('## Subarea Quality Matrix')
  lines.push('')
  lines.push('| Subarea | Surface | Comparator | Critique | Decision |')
  lines.push('| --- | --- | --- | --- | --- |')
  for (const subarea of subareaMatrix) lines.push(`| ${subarea.area} | \`${subarea.surface}\` | ${subarea.comparator} | ${subarea.critique} | ${subarea.decision} |`)
  lines.push('')
  lines.push('## Summary')
  for (const result of results) lines.push(`- \`${result.id}\`: ${result.total} (limit ${result.limit})`)
  lines.push('')
  lines.push('## Findings')
  for (const result of results) {
    lines.push(`### ${result.id}`)
    lines.push('')
    lines.push(result.description)
    lines.push('')
    lines.push('| File | Count | Note |')
    lines.push('| --- | ---: | --- |')
    for (const item of result.fileResults) lines.push(`| \`${fileLabel(item.file)}\` | ${item.value} | ${item.note} |`)
    lines.push('')
  }
  lines.push('## Policy')
  lines.push('')
  lines.push('- Public pages must show a compact workflow, not decorative proof walls.')
  lines.push('- Public chrome is a design-system surface and should not drift into inline styling.')
  lines.push('- Marketplace install flows must expose trust, permissions, provenance, and risk before mutation.')
  lines.push('- Locale mixing is blocked on the landing spine until i18n owns route-level language selection.')
  lines.push('')

  fs.writeFileSync(reportFile, `${lines.join('\n').trimEnd()}\n`, 'utf8')
  return rel(root, reportFile)
}
