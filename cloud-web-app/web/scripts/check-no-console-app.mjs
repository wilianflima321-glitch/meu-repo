import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const cwd = process.cwd()
const webRoot = existsSync(path.join(cwd, 'app')) ? cwd : path.join(cwd, 'cloud-web-app', 'web')
const appRoot = path.join(webRoot, 'app')
const docsRoot = path.join(webRoot, 'docs')
const reportPath = path.join(docsRoot, 'NO_CONSOLE_APP_SPINE.md')

const DEFAULT_BUDGET = 0
const budget = Number.parseInt(process.env.AETHEL_CONSOLE_APP_BUDGET ?? `${DEFAULT_BUDGET}`, 10)
const consolePattern = /\bconsole\.(log|warn|error|info|debug|trace)\s*\(/g
const sourceExtensions = new Set(['.ts', '.tsx'])
const ignoredSegments = new Set(['node_modules', '.next', 'coverage'])

function walk(dir, files = []) {
  if (!existsSync(dir)) {
    return files
  }

  for (const entry of readdirSync(dir)) {
    if (ignoredSegments.has(entry)) {
      continue
    }

    const absolute = path.join(dir, entry)
    const stats = statSync(absolute)

    if (stats.isDirectory()) {
      walk(absolute, files)
      continue
    }

    if (sourceExtensions.has(path.extname(entry))) {
      files.push(absolute)
    }
  }

  return files
}

function relativeToWeb(file) {
  return path.relative(webRoot, file).replaceAll(path.sep, '/')
}

const findings = []

for (const file of walk(appRoot)) {
  const content = readFileSync(file, 'utf8')
  const lines = content.split(/\r?\n/)

  lines.forEach((line, index) => {
    const matches = line.match(consolePattern)
    if (!matches) {
      return
    }

    findings.push({
      file: relativeToWeb(file),
      line: index + 1,
      count: matches.length,
      sample: line.trim().slice(0, 140),
    })
  })
}

const byFile = new Map()
for (const finding of findings) {
  const current = byFile.get(finding.file) ?? { file: finding.file, count: 0, firstLine: finding.line }
  current.count += finding.count
  current.firstLine = Math.min(current.firstLine, finding.line)
  byFile.set(finding.file, current)
}

const topFiles = [...byFile.values()].sort((a, b) => b.count - a.count || a.file.localeCompare(b.file))
const total = findings.reduce((sum, finding) => sum + finding.count, 0)

mkdirSync(docsRoot, { recursive: true })

const topRows = topFiles
  .slice(0, 30)
  .map((item) => `| ${item.file} | ${item.count} | ${item.firstLine} |`)
  .join('\n')

const sampleRows = findings
  .slice(0, 40)
  .map((item) => `| ${item.file}:${item.line} | \`${item.sample.replaceAll('|', '\\|')}\` |`)
  .join('\n')

const report = `# No Console App Spine

Generated by \`npm run qa:no-console-app\`.

## Current Budget

| Metric | Value |
| --- | ---: |
| Current app console calls | ${total} |
| Regression budget | ${budget} |
| Target | 0 |

This gate is intentionally progressive: it prevents new \`console.*\` debt in \`app/\` while the legacy API/admin routes are consolidated. Replace production logging with the canonical logger so Sentry, OpenTelemetry, and support signals stay usable internationally.

## Top Offenders

| File | Count | First line |
| --- | ---: | ---: |
${topRows || '| None | 0 | - |'}

## First Samples

| Location | Sample |
| --- | --- |
${sampleRows || '| None | - |'}

## Policy

- Route handlers should use the server logger instead of raw \`console.*\`.
- UI routes should report user-facing failures through inline state, toast, or error boundaries.
- Temporary debugging must stay in local branches and never increase this budget.
- Ratchet path: reduce \`AETHEL_CONSOLE_APP_BUDGET\` after each cleanup wave until the default can become 0.
`

writeFileSync(reportPath, report)

if (total > budget) {
  console.error(`No-console app gate failed: found ${total} console calls, budget is ${budget}.`)
  console.error(`Report: ${reportPath}`)
  process.exit(1)
}

console.log(`No-console app gate passed: ${total}/${budget} console calls.`)
console.log(`Report: ${reportPath}`)
