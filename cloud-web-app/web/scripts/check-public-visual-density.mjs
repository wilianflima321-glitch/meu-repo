#!/usr/bin/env node

import fs from 'node:fs'
import path from 'node:path'

const ROOT = process.cwd()
const DOCS_DIR = path.join(ROOT, 'docs')
const REPORT_FILE = path.join(DOCS_DIR, 'PUBLIC_VISUAL_DENSITY_SPINE.md')

const PUBLIC_SURFACES = [
  'app/page.tsx',
  'app/landing-v3.tsx',
  'app/landing-v3-mission-box.tsx',
  'app/landing-v3-studio-proof.tsx',
  'app/pricing/page.tsx',
  'app/compare/page.tsx',
  'app/customers/page.tsx',
  'app/contact/page.tsx',
  'app/contact/contact-content.tsx',
  'app/contact-sales/page.tsx',
  'app/contact-sales/contact-sales-content.tsx',
  'app/download/page.tsx',
  'app/help/page.tsx',
  'app/status/page.tsx',
  'app/trust/page.tsx',
  'app/security/page.tsx',
  'app/security-policy/page.tsx',
  'app/security-acknowledgments/page.tsx',
  'app/compliance/page.tsx',
  'app/reliability/page.tsx',
  'app/roadmap/page.tsx',
  'app/honest-status/page.tsx',
  'app/marketplace/page.tsx',
  'app/marketplace/marketplace-page.data.ts',
  'app/(auth)/login/login-v2.tsx',
  'app/(auth)/register/register-v2.tsx',
  'components/auth/AuthExperiencePanel.tsx',
  'components/ui/PublicHeader.tsx',
  'components/ui/PublicFooter.tsx',
]

const RULES = [
  {
    id: 'screenshot-billboard-source',
    label: 'Public surface uses raw screenshot billboard source',
    regex: /src=["']\/screenshots\//g,
    limit: 0,
  },
  {
    id: 'priority-marketing-media',
    label: 'Public surface prioritizes marketing media instead of functional UI',
    regex: /<Image[\s\S]{0,420}\bpriority\b[\s\S]{0,420}\/screenshots\//g,
    limit: 0,
  },
  {
    id: 'giant-public-media-class',
    label: 'Public surface uses wide object-cover media likely to become a billboard',
    regex: /<Image[\s\S]{0,520}(w-full[\s\S]{0,120}object-cover|object-cover[\s\S]{0,120}w-full)/g,
    limit: 0,
  },
  {
    id: 'raw-public-img',
    label: 'Public surface uses raw img tag outside sanctioned avatar/collab contexts',
    regex: /<img\b/g,
    limit: 0,
  },
]

function rel(pathLike) {
  return pathLike.replace(/\\/g, '/')
}

function countMatches(content, regex) {
  const re = new RegExp(regex.source, regex.flags)
  let count = 0
  while (re.exec(content)) count += 1
  return count
}

function main() {
  const scanned = []
  const missing = []
  const results = RULES.map((rule) => ({ ...rule, total: 0, files: [] }))

  for (const relFile of PUBLIC_SURFACES) {
    const abs = path.join(ROOT, relFile)
    if (!fs.existsSync(abs)) {
      missing.push(relFile)
      continue
    }

    scanned.push(relFile)
    const content = fs.readFileSync(abs, 'utf8')
    for (const result of results) {
      const count = countMatches(content, result.regex)
      if (count > 0) {
        result.total += count
        result.files.push({ file: relFile, count })
      }
    }
  }

  fs.mkdirSync(DOCS_DIR, { recursive: true })
  const lines = []
  lines.push('# Public Visual Density Spine')
  lines.push('')
  lines.push('Generated by `npm run qa:public-visual-density`. This gate keeps public surfaces useful, compact, and evidence-led instead of screenshot billboards.')
  lines.push('')
  lines.push('## Summary')
  lines.push(`- Files scanned: ${scanned.length}`)
  lines.push(`- Missing optional surfaces: ${missing.length}`)
  for (const result of results) {
    lines.push(`- \`${result.id}\`: ${result.total} (limit ${result.limit})`)
  }
  lines.push('')
  lines.push('## Scanned Surfaces')
  for (const file of scanned.sort()) lines.push(`- \`${rel(file)}\``)
  if (missing.length > 0) {
    lines.push('')
    lines.push('## Missing Optional Surfaces')
    for (const file of missing.sort()) lines.push(`- \`${rel(file)}\``)
  }
  lines.push('')
  lines.push('## Findings')
  for (const result of results) {
    lines.push(`### ${result.label}`)
    lines.push('')
    lines.push(`- Metric ID: \`${result.id}\``)
    lines.push(`- Total matches: \`${result.total}\``)
    lines.push(`- Limit: \`${result.limit}\``)
    lines.push('')
    if (result.files.length === 0) {
      lines.push('- No matches')
      lines.push('')
      continue
    }
    lines.push('| File | Matches |')
    lines.push('| --- | ---: |')
    for (const item of result.files.sort((a, b) => b.count - a.count || a.file.localeCompare(b.file))) {
      lines.push(`| \`${rel(item.file)}\` | ${item.count} |`)
    }
    lines.push('')
  }
  lines.push('## Policy')
  lines.push('')
  lines.push('- Public entry routes should show task flow, state, proof, and compact product grammar before decorative media.')
  lines.push('- Screenshot or dashboard imagery belongs behind explicit case-study/detail pages, never as the default hero proof.')
  lines.push('- Small brand marks are allowed; giant raw product screenshots are not.')
  lines.push('')
  fs.writeFileSync(REPORT_FILE, `${lines.join('\n')}\n`, 'utf8')

  const failures = results
    .filter((result) => result.total > result.limit)
    .map((result) => `${result.id}=${result.total} (limit=${result.limit})`)

  if (failures.length > 0) {
    console.error(`[public-visual-density] FAIL ${failures.join(', ')}`)
    console.error(`report=${rel(path.relative(ROOT, REPORT_FILE))}`)
    process.exit(1)
  }

  console.log(`[public-visual-density] PASS files=${scanned.length} ${results.map((r) => `${r.id}=${r.total}`).join(' ')}`)
}

main()
