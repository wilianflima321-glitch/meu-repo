#!/usr/bin/env node

import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'

const WEB_ROOT = process.cwd()
const REPORT_FILE = path.join(WEB_ROOT, 'docs', 'WCAG_CRITICAL_SURFACE_AUDIT.md')

function read(relativePath) {
  const absolutePath = path.join(WEB_ROOT, relativePath)
  if (!fs.existsSync(absolutePath)) {
    throw new Error(`Missing file: ${relativePath}`)
  }
  return fs.readFileSync(absolutePath, 'utf8')
}

const CHECKS = [
  {
    name: 'landing-skip-link',
    file: 'app/landing-v3.tsx',
    surface: '/',
    patterns: ['<main id="main-content"', 'href="/dashboard?onboarding=1&source=landing-primary-cta"'],
  },
  {
    name: 'dashboard-hydration-loading',
    file: 'app/dashboard/page.tsx',
    surface: '/dashboard',
    patterns: ['Loading Studio Home...', 'role="status"', 'aria-live="polite"'],
  },
  {
    name: 'dashboard-main-skip-link',
    file: 'components/dashboard/DashboardShell.tsx',
    surface: '/dashboard',
    patterns: ['href="#dashboard-main-content"', '<main id="dashboard-main-content"', 'aria-live="polite"'],
  },
  {
    name: 'dashboard-menu-controls',
    file: 'components/dashboard/DashboardHeader.tsx',
    surface: '/dashboard',
    patterns: ['aria-expanded={sidebarOpen}', 'aria-controls="dashboard-sidebar"'],
  },
  {
    name: 'dashboard-sidebar-mobile-close',
    file: 'components/dashboard/AethelDashboardSidebar.tsx',
    surface: '/dashboard',
    patterns: ['id="dashboard-sidebar"', 'aria-label="Close navigation"'],
  },
  {
    name: 'admin-shell-landmarks',
    file: 'app/admin/admin-ops-layout-client.tsx',
    surface: '/admin',
    patterns: ['role="navigation"', 'aria-label="Admin navigation"', '<main id="admin-main-content"', 'aria-label="Global Legacy compatibility map"'],
  },
  {
    name: 'admin-command-center-copy',
    file: 'components/admin/AdminCommandCenterSections.tsx',
    surface: '/admin',
    patterns: ['Six areas, no orphaned admin intent', 'legacy routes remain compatible'],
  },
  {
    name: 'login-accessibility-baseline',
    file: 'app/(auth)/login/login-v2.tsx',
    surface: '/login',
    patterns: ['href="#login-form"', '<main className=', 'aria-describedby={formError ? \'login-form-error\' : undefined}'],
  },
  {
    name: 'register-accessibility-baseline',
    file: 'app/(auth)/register/register-v2.tsx',
    surface: '/register',
    patterns: ['href="#register-form"', '<main className=', 'aria-describedby={formError ? \'register-form-error\' : undefined}'],
  },
  {
    name: 'settings-provider-recovery',
    file: 'app/settings/page.tsx',
    surface: '/settings',
    patterns: ['/api/ai/provider-status', "providerStatus?.setupUrl || '/settings?tab=api'"],
  },
  {
    name: 'ide-workbench-runtime-accessibility',
    file: 'components/ide/FullscreenIDE.tsx',
    surface: '/ide',
    patterns: ['Suspense', 'role="status"'],
  },
]

const failures = []

for (const check of CHECKS) {
  const content = read(check.file)
  for (const pattern of check.patterns) {
    if (!content.includes(pattern)) {
      failures.push(`[${check.name}] pattern not found in ${check.file}: ${pattern}`)
    }
  }
}

const report = [
  '# WCAG Critical Surface Audit',
  '',
  'Generated by `npm run qa:wcag-critical`. This is a deterministic static P1-R evidence gate; runtime axe evidence remains a separate promotion requirement.',
  '',
  '## Surfaces audited',
  ...[...new Set(CHECKS.map((check) => check.surface))].map((surface) => `- ${surface}`),
  '',
  '## Static evidence checks',
  '| Check | Surface | File | Status |',
  '| --- | --- | --- | --- |',
  ...CHECKS.map((check) => {
    const failed = failures.some((failure) => failure.startsWith(`[${check.name}]`))
    return `| ${check.name} | ${check.surface} | \`${check.file}\` | ${failed ? 'fail' : 'pass'} |`
  }),
  '',
  '## Open gaps before WCAG AA claim',
  '- Run runtime axe/Lighthouse contrast verification across light/dark dashboard, IDE, and admin flows.',
  '- Reduce runtime audit threshold below `maxViolationsPerPage=20` only after reproducible evidence is stored in CI artifacts.',
  '- Keep accessibility readiness `PARTIAL` until runtime evidence covers keyboard, contrast, labels, and motion reduction end-to-end.',
  '',
  '## Failures',
  ...(failures.length ? failures.map((failure) => `- ${failure}`) : ['- none']),
]

fs.mkdirSync(path.dirname(REPORT_FILE), { recursive: true })
fs.writeFileSync(REPORT_FILE, `${report.join('\n')}\n`, 'utf8')

if (failures.length > 0) {
  console.error('[wcag-critical] FAIL')
  for (const failure of failures) {
    console.error(` - ${failure}`)
  }
  process.exit(1)
}

console.log(`[wcag-critical] PASS checks=${CHECKS.length}`)
