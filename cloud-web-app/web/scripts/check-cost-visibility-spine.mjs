#!/usr/bin/env node

import fs from 'node:fs'
import path from 'node:path'

const ROOT = process.cwd()
const DOCS_DIR = path.join(ROOT, 'docs')
const REPORT_FILE = path.join(DOCS_DIR, 'COST_VISIBILITY_SPINE.md')

const REQUIREMENTS = [
  {
    id: 'cost-meter-component',
    file: 'components/cost/CostMeter.tsx',
    patterns: [/getStudioCostLive\(/, /avgCostPerRequestUsd/, /budget\.monthly\.percent/],
  },
  {
    id: 'cost-live-api-route',
    file: 'app/api/studio/cost/live/route.ts',
    patterns: [/buildBudgetMeter/, /emergencyMetrics/, /avgCostPerRequestUsd/],
  },
  {
    id: 'api-client-cost-method',
    file: 'lib/api.ts',
    patterns: [/getStudioCostLive/, /\/studio\/cost\/live/],
  },
  {
    id: 'ide-header-cost-visible',
    file: 'components/ide/fullscreen/FullscreenIDEWorkspace.tsx',
    patterns: [/CostMeter/, /headerExtras/],
  },
  {
    id: 'dashboard-header-cost-visible',
    file: 'components/dashboard/DashboardShell.tsx',
    patterns: [/CostMeter/, /extraActions=\{<CostMeter \/>\}/],
  },
]

function rel(filePath) {
  return filePath.replace(/\\/g, '/')
}

function main() {
  const failures = []
  const lines = []
  lines.push('# Cost Visibility Spine')
  lines.push('')
  lines.push('Generated by `npm run qa:cost-visibility-spine`. Cost visibility is a trust surface: agent spend and budget state must remain visible before users launch long-running work.')
  lines.push('')
  lines.push('## Summary')

  const rows = []
  for (const requirement of REQUIREMENTS) {
    const abs = path.join(ROOT, requirement.file)
    if (!fs.existsSync(abs)) {
      failures.push(`${requirement.id}: missing ${requirement.file}`)
      rows.push({ ...requirement, status: 'missing', missing: requirement.patterns.length })
      continue
    }

    const content = fs.readFileSync(abs, 'utf8')
    const missingPatterns = requirement.patterns.filter((pattern) => !pattern.test(content))
    if (missingPatterns.length > 0) {
      failures.push(`${requirement.id}: ${missingPatterns.length} contract pattern(s) missing in ${requirement.file}`)
    }
    rows.push({ ...requirement, status: missingPatterns.length === 0 ? 'pass' : 'fail', missing: missingPatterns.length })
  }

  lines.push(`- Requirements checked: ${REQUIREMENTS.length}`)
  lines.push(`- Failures: ${failures.length}`)
  lines.push('')
  lines.push('## Requirements')
  lines.push('')
  lines.push('| Requirement | File | Status | Missing patterns |')
  lines.push('| --- | --- | --- | ---: |')
  for (const row of rows) {
    lines.push(`| \`${row.id}\` | \`${rel(row.file)}\` | ${row.status} | ${row.missing} |`)
  }
  lines.push('')
  lines.push('## Policy')
  lines.push('')
  lines.push('- Cost must be visible in the IDE and dashboard before users launch expensive agent/runtime work.')
  lines.push('- Billing readiness alone is not enough; per-request cost and monthly budget pressure must stay inspectable.')
  lines.push('- Do not hide cost state behind admin-only surfaces.')
  lines.push('')

  fs.mkdirSync(DOCS_DIR, { recursive: true })
  fs.writeFileSync(REPORT_FILE, `${lines.join('\n')}\n`, 'utf8')

  if (failures.length > 0) {
    console.error('[cost-visibility-spine] FAIL')
    for (const failure of failures) console.error(`- ${failure}`)
    console.error(`report=${rel(path.relative(ROOT, REPORT_FILE))}`)
    process.exit(1)
  }

  console.log(`[cost-visibility-spine] PASS requirements=${REQUIREMENTS.length}`)
}

main()
