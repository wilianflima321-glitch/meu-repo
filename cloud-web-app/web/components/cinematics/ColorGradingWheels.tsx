// ── Main Color Grading Panel ───────────────────────────────────────────────

interface ColorGradingWheelsProps {
  config?: ColorGradingConfig;
  onChange?: (config: ColorGradingConfig) => void;
}

export function ColorGradingWheels({
  config = DEFAULT_COLOR_GRADING,
  onChange,
}: ColorGradingWheelsProps) {
  const [current, setCurrent] = useState<ColorGradingConfig>(config);

  const update = <K extends keyof ColorGradingConfig>(key: K, value: ColorGradingConfig[K]) => {
    const next = { ...current, [key]: value };
    setCurrent(next);
    onChange?.(next);
  };

  const handleResetAll = () => {
    setCurrent(DEFAULT_COLOR_GRADING);
    onChange?.(DEFAULT_COLOR_GRADING);
  };

  const handleExportCubeLUT = () => {
    const cubeContent = generate3DLutCube(current);
    const blob = new Blob([cubeContent], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `Aethel_Grade_ACES_${Date.now()}.cube`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6 rounded-2xl border border-[var(--aethel-border-subtle)] bg-[color-mix(in_srgb,var(--aethel-surface-secondary)_50%,transparent)] p-5 backdrop-blur-xl">
      {/* Top Header */}
      <div className="flex items-center justify-between border-b border-[var(--aethel-border-subtle)] pb-3">
        <div>
          <h3 className="text-sm font-bold uppercase tracking-wider text-[var(--aethel-text-primary)]">
            Color Grading (ACES 1.3 HDR)
          </h3>
          <p className="text-[11px] text-[var(--aethel-text-tertiary)]">
            3-Way HDR Wheels, Kelvin Temperature, and DaVinci / UE5 .CUBE LUT Export
          </p>
        </div>
        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={handleExportCubeLUT}
            className="inline-flex items-center gap-1.5 rounded-lg border border-[color-mix(in_srgb,var(--aethel-neon-cyan)_40%,transparent)] bg-[color-mix(in_srgb,var(--aethel-neon-cyan)_12%,transparent)] px-3 py-1.5 text-xs font-semibold text-[var(--aethel-neon-cyan)] hover:bg-[color-mix(in_srgb,var(--aethel-neon-cyan)_22%,transparent)] transition-all active:scale-95 shadow-sm"
            title="Export 3D LUT (.CUBE) for Unreal Engine 5 or DaVinci Resolve"
          >
            <FileDown className="h-3.5 w-3.5" /> Export .CUBE LUT
          </button>
          <button
            type="button"
            onClick={handleResetAll}
            className="inline-flex items-center gap-1.5 rounded-lg border border-[var(--aethel-border-subtle)] bg-[color-mix(in_srgb,var(--aethel-surface-tertiary)_60%,transparent)] px-3 py-1.5 text-xs font-semibold text-[var(--aethel-text-secondary)] hover:text-[var(--aethel-text-primary)] transition-all active:scale-95"
          >
            <RotateCcw className="h-3.5 w-3.5" /> Reset All
          </button>
        </div>
      </div>

      {/* 4-Way Color Wheels Grid (Lift, Gamma, Gain, Offset) */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
        <ColorWheel
          label="Lift"
          subtitle="Shadows / Black Point"
          value={current.lift}
          onChange={(v) => update('lift', v)}
          accentColor="var(--aethel-info)"
        />
        <ColorWheel
          label="Gamma"
          subtitle="Midtones / Exposure"
          value={current.gamma}
          onChange={(v) => update('gamma', v)}
          accentColor="var(--aethel-success)"
        />
        <ColorWheel
          label="Gain"
          subtitle="Highlights / White Point"
          value={current.gain}
          onChange={(v) => update('gain', v)}
          accentColor="var(--aethel-warning)"
        />
        <ColorWheel
          label="Offset"
          subtitle="Master Color Balance"
          value={current.offset}
          onChange={(v) => update('offset', v)}
          accentColor="var(--aethel-primary)"
        />
      </div>

      {/* Secondary Controls & RGB Parade Grid */}
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6 pt-2 border-t border-[var(--aethel-border-subtle)]">
        {/* Sliders for Temp, Tint, Contrast, Saturation */}
        <div className="space-y-4">
          {/* Temperature Kelvin */}
          <div>
            <div className="flex justify-between text-xs mb-1">
              <span className="font-semibold text-[var(--aethel-text-secondary)] flex items-center gap-1">
                <Thermometer className="h-3.5 w-3.5 text-[var(--aethel-warning)]" /> Temperature
              </span>
              <span className="font-mono text-[var(--aethel-text-primary)]">{current.temperature}K</span>
            </div>
            <input
              type="range"
              min={2000}
              max={12000}
              step={50}
              value={current.temperature}
              onChange={(e) => update('temperature', parseInt(e.target.value, 10))}
              className="w-full cursor-pointer"
            />
          </div>

          {/* Tint */}
          <div>
            <div className="flex justify-between text-xs mb-1">
              <span className="font-semibold text-[var(--aethel-text-secondary)]">Tint (Green / Magenta)</span>
              <span className="font-mono text-[var(--aethel-text-primary)]">
                {current.tint > 0 ? `+${current.tint}` : current.tint}
              </span>
            </div>
            <input
              type="range"
              min={-100}
              max={100}
              value={current.tint}
              onChange={(e) => update('tint', parseInt(e.target.value, 10))}
              className="w-full cursor-pointer"
            />
          </div>

          {/* Contrast & Saturation Row */}
          <div className="grid grid-cols-2 gap-4">
            <div>
              <div className="flex justify-between text-xs mb-1">
                <span className="font-semibold text-[var(--aethel-text-secondary)]">Contrast</span>
                <span className="font-mono text-[var(--aethel-text-primary)]">{current.contrast.toFixed(2)}x</span>
              </div>
              <input
                type="range"
                min={0.5}
                max={2.0}
                step={0.01}
                value={current.contrast}
                onChange={(e) => update('contrast', parseFloat(e.target.value))}
                className="w-full cursor-pointer"
              />
            </div>

            <div>
              <div className="flex justify-between text-xs mb-1">
                <span className="font-semibold text-[var(--aethel-text-secondary)]">Master Saturation</span>
                <span className="font-mono text-[var(--aethel-text-primary)]">
                  {Math.round(current.saturation * 100)}%
                </span>
              </div>
              <input
                type="range"
                min={0}
                max={2.0}
                step={0.01}
                value={current.saturation}
                onChange={(e) => update('saturation', parseFloat(e.target.value))}
                className="w-full cursor-pointer"
              />
            </div>
          </div>
        </div>

        {/* RGB Parade Scope Visualizer */}
        <RGBParadeScope />
      </div>
    </div>
  );
}
